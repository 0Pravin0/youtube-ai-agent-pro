"use client";
import { useRef, useState } from "react";
import { api, useApi } from "@/lib/api";
import { getEngine } from "@/lib/engine";
import { Button, Field, inputCls } from "./ui";

/** Background music the owner is licensed to use. Only tracks added here (with a licence note) are
 * ever mixed into videos; with none, videos are narration-only. */
export function MusicLibrary({ toast }: { toast: (m: string, bad?: boolean) => void }) {
  const { data, reload } = useApi<any[]>("/music");
  const fileRef = useRef<HTMLInputElement>(null);
  const [title, setTitle] = useState("");
  const [license, setLicense] = useState("");
  const [moods, setMoods] = useState("");
  const [kind, setKind] = useState("music");
  const [attribution, setAttribution] = useState("");
  const [busy, setBusy] = useState(false);

  const add = async () => {
    const f = fileRef.current?.files?.[0];
    if (!f) return toast("Choose an audio file first", true);
    setBusy(true);
    try {
      const eng = await getEngine();
      const fd = new FormData();
      fd.append("file", f);
      fd.append("title", title || f.name);
      fd.append("license", license);
      fd.append("moods", moods);
      fd.append("kind", kind);
      fd.append("attribution", attribution);
      const r = await fetch(`${eng.url}/api/music`, { method: "POST", headers: { "x-yta-token": eng.token }, body: fd });
      if (!r.ok) throw new Error((await r.json()).detail || r.statusText);
      setTitle(""); setLicense(""); setMoods(""); setAttribution("");
      if (fileRef.current) fileRef.current.value = "";
      toast("Track added"); reload();
    } catch (e: any) { toast(String(e.message || e), true); } finally { setBusy(false); }
  };
  const remove = async (file: string) => {
    try { await api(`/music/${encodeURIComponent(file)}`, { method: "DELETE" }); reload(); } catch (e: any) { toast(e.message, true); }
  };

  return (
    <div className="space-y-4">
      {(data || []).length > 0 ? (
        <ul className="divide-y divide-[var(--line)] rounded-xl border border-[var(--line)]">
          {data!.map((t) => (
            <li key={t.file} className="flex items-center justify-between gap-3 px-4 py-2.5 text-[14px]">
              <span className="min-w-0"><b className="font-medium">{t.title}</b> <span className="text-[var(--muted)]">· {t.kind === "sfx" ? "sound effect" : "music"} · {Math.round(t.duration_s)} s · {t.moods.join(", ") || "any mood"}</span>
                <span className="block truncate text-[12px] text-[var(--muted)]">Licence: {t.license}{t.attribution ? ` · Attribution: ${t.attribution}` : ""}</span></span>
              <Button kind="ghost" onClick={() => remove(t.file)}>Remove</Button>
            </li>
          ))}
        </ul>
      ) : <p className="text-[14px] text-[var(--muted)]">Nothing added yet. Until you add music you're allowed to use on YouTube (for example from the YouTube Audio Library), videos get an original background pad and sound effects generated by the app itself, so no third-party rights are involved.</p>}
      <div className="grid gap-3 rounded-xl border border-dashed border-[var(--line)] p-4 sm:grid-cols-2">
        <Field label="Audio file (MP3, WAV, M4A…)"><input ref={fileRef} type="file" accept=".mp3,.wav,.m4a,.aac,.ogg,.flac,audio/*" className="text-[14px]" /></Field>
        <Field label="Type"><select className={inputCls} value={kind} onChange={(e) => setKind(e.target.value)}><option value="music">Background music</option><option value="sfx">Sound effect / ambience</option></select></Field>
        <Field label="Title"><input className={inputCls} value={title} onChange={(e) => setTitle(e.target.value)} placeholder="Calm forest" /></Field>
        <Field label="Licence" hint="Where it's from and that YouTube use is allowed"><input className={inputCls} value={license} onChange={(e) => setLicense(e.target.value)} placeholder="YouTube Audio Library, no attribution required" /></Field>
        <Field label="Attribution (if the licence requires it)" hint="Added to the video description"><input className={inputCls} value={attribution} onChange={(e) => setAttribution(e.target.value)} placeholder="Music: Artist – Title (CC BY 4.0)" /></Field>
        <Field label="Moods / sound tags (comma separated)" hint="Used to match each story or scene, e.g. rain, birds, magic"><input className={inputCls} value={moods} onChange={(e) => setMoods(e.target.value)} placeholder="calm, magical, adventure" /></Field>
        <div><Button disabled={busy || license.trim().length < 5} onClick={add}>{busy ? "Adding…" : "Add track"}</Button></div>
      </div>
    </div>
  );
}
